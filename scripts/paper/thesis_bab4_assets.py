"""Build thesis Chapter IV tables/validation curves from archived results; no inference.
Run: python3 scripts/paper/thesis_bab4_assets.py
Inputs are frozen six-class runs, final four-class local/lab exports, target V4,
and archived IEEE country table (rounded subgroup metrics).
"""
from pathlib import Path
import csv
import json
import hashlib
import shutil
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter

ROOT = Path(__file__).resolve().parents[2]
BOOK = ROOT / 'latex/buku-ta-template'
S = ROOT / 'runs/rdd_yolov8n_local'
MODELS = dict(zip(['yolov8n', 'yolov12n', 'yolov26n', 'yolov8_pd', 'yolo_rd'],
                  ['YOLOv8n', 'YOLOv12n', 'YOLO26n', 'YOLOv8-PD', 'YOLO-RD']))
inputs = set()

def read(path):
    inputs.add(path)
    return list(csv.DictReader(path.open()))

def mean(rows, key):
    return sum(float(r[key]) for r in rows) / len(rows)

def fmt(x, digits=3):
    return f'{x:.{digits}f}'.replace('.', ',')

def table(name, caption, heads, rows):
    text = [r'% Generated by scripts/paper/thesis_bab4_assets.py; see build/bab4-qa/evidence.json.',
            r'\begin{table}[H]', r'\centering', r'\caption{' + caption + '}',
            r'\label{tab:b4-' + name + '}', r'\begingroup\fontsize{10}{13}\selectfont',
            r'\setlength{\tabcolsep}{3pt}',
            r'\begin{tabularx}{\linewidth}{|X|' + 'r|' * (len(heads)-1) + r'}\hline',
            r'\rowcolor{black}' + '&'.join(r'\HeaderTabel{' + h + '}' for h in heads) + r'\\\hline']
    text.extend(' & '.join(map(str, row)) + r'\\\hline' for row in rows)
    text += [r'\end{tabularx}\endgroup', r'\end{table}', '']
    (BOOK / 'tabel' / f'bab4-{name}.tex').write_text('\n'.join(text))

src, target, history, ablation = {}, {}, {}, {}
zs = read(S/'evaluation/zero_shot_indo_v4/zs_per_class_metrics.csv')
complexity_path = S/'model_complexity.json'
inputs.add(complexity_path)
complexity = json.loads(complexity_path.read_text())['models']
overlap = {r['model']: int(r['n_true']) for r in read(S/'fp_overlap_6cls_vs_4cls_test.csv')}
training, overall, perclass, efficiency, abl, transfer, targets, five = [], [], [], [], [], [], [], []
for m, label in MODELS.items():
    src[m] = read(S/f'{m}_class_weight_test_per_class_metrics.csv')
    assert [int(r['class_id']) for r in src[m]] == list(range(6))
    assert sum(float(r['support']) for r in src[m]) == 2425
    target[m] = [r for r in zs if r['model'] == m and r['evaluated'] == 'True']
    assert sum(float(r['support']) for r in target[m]) == 502
    history[m] = [{k.strip(): float(v) for k, v in row.items()} for row in read(S/'experiments'/f'{m}_class_weight'/'results.csv')]
    h = history[m]
    best = max(h, key=lambda r:r['metrics/mAP50-95(B)'])
    assert int(h[-1]['epoch']) == len(h)
    training.append([label, int(best['epoch']), len(h), fmt(h[-1]['time']/3600, 2)])
    overall.append([label] + [fmt(mean(src[m], k)) for k in ['precision','recall','mAP50','mAP50-95','f1']])
    perclass.append([label] + [fmt(float(r['mAP50'])) for r in src[m]])
    summary_path = S/f'{m}_class_weight_summary.json'
    inputs.add(summary_path)
    summary = json.loads(summary_path.read_text())
    fps = summary['test_fps_estimate']
    speed = summary['test_speed_ms_per_image']
    assert abs(fps - 1000/sum(speed[k] for k in ['preprocess','inference','postprocess'])) < .01
    efficiency.append([label, fmt(complexity[m]['params_M'],2), fmt(complexity[m]['gflops'],1), fmt(fps,1)])
    folder = 'rdd_4class_local_pc_lab' if m in ['yolov8n','yolov12n','yolov26n'] else 'rdd_4class_local'
    a = read(ROOT/'runs'/folder/f'{m}_4cls_class_weights_test_per_class_metrics.csv')
    ablation[m] = a
    s4, a4 = mean(src[m][:4], 'mAP50'), mean(a, 'mAP50')
    abl.append([label, fmt(s4,4), fmt(a4,4), ('+' if a4>=s4 else '')+fmt(a4-s4,4), overlap[m+'_6cls'], overlap[m+'_4cls']])
    t4 = mean(target[m][:4], 'mAP50')
    transfer.append([label, fmt(s4), fmt(t4), fmt(100*(s4-t4),2), fmt(100*(1-t4/s4),1)])
    targets.append([label]+[fmt(float(r['mAP50'])) for r in target[m]])
    s5 = mean([r for r in src[m] if int(r['class_id'])!=4], 'mAP50')
    t5 = mean(target[m], 'mAP50')
    five.append([label,fmt(s5),fmt(t5),fmt(100*(1-t5/s5),1)])

table('pelatihan','Ringkasan pelaksanaan pelatihan utama enam kelas.', ['Model','Epoch terbaik','Epoch akhir','Waktu (jam)'],training)
table('sumber','Hasil pengujian sumber pada enam kelas.', ['Model','Presisi','Recall','mAP@0,5','mAP@0,5:0,95','F1 makro'],overall)
table('kelas-sumber','AP@0,5 per kelas pada data uji sumber.', ['Model','D00','D10','D20','D40','D70','D80'],perclass)
table('efisiensi','Kompleksitas dan estimasi kecepatan model enam kelas.', ['Model','Parameter (juta)','GFLOPs','FPS estimasi'],efficiency)
table('ablasi','Perbandingan pelatihan enam dan empat kelas pada data uji sumber.', ['Model','mAP 6','mAP 4',r'$\Delta$ mAP','Kotak 6','Kotak 4'],abl)
table('transfer','Perbandingan mAP@0,5 empat kelas kerusakan pada sumber dan target.', ['Model','Sumber','Target',r'Selisih (pp)',r'Turun (\%)'],transfer)
table('kelas-target','AP@0,5 per kelas pada data target Indonesia.', ['Model','D00','D10','D20','D40','D80'],targets)
table('lima-kelas','Evaluasi tambahan mAP@0,5 pada lima kelas bersama.', ['Model','Sumber','Target',r'Turun (\%)'],five)
# Rounded country aggregates from the final manuscript, corroborated by notebook outputs.
# Do not derive extra precision from the printed three-decimal per-class notebook log.
inputs.update([ROOT/'latex/IEEE-Conference/main.tex', ROOT/'code/06_per_country_analysis.ipynb'])
country = [[.931,.578,.284],[.933,.579,.293],[.933,.543,.305],[.953,.567,.299],[.945,.587,.304]]
table('negara','mAP@0,5 empat kelas kerusakan menurut negara sumber.', ['Model','Tiongkok','Jepang','India'], [[label]+[fmt(v) for v in values] for label,values in zip(MODELS.values(),country)])

plt.rcParams.update({'font.family':'DejaVu Sans','font.size':10,'pdf.fonttype':42})
fig, axes = plt.subplots(2,1,figsize=(7.2,6.4),sharex=True)
colors = ['#0072B2','#D55E00','#009E73','#CC79A7','#222222']
styles = ['-','--','-.',':','-']
for m,color,style in zip(MODELS,colors,styles):
    h=history[m]
    best=max(h,key=lambda r:r['metrics/mAP50-95(B)'])
    for ax,key in zip(axes,['metrics/mAP50(B)','metrics/mAP50-95(B)']):
        ax.plot([r['epoch'] for r in h],[r[key] for r in h],label=MODELS[m],color=color,ls=style,lw=1.25)
        ax.scatter(best['epoch'],best[key],s=28,color=color,zorder=5,edgecolor='white',linewidth=.5)
for ax,title,ymax in zip(axes,['(a) mAP@0,5 validasi','(b) mAP@0,5:0,95 validasi'],[.72,.42]):
    ax.set_ylabel(title); ax.set_ylim(0,ymax); ax.set_xlim(0,300)
    ax.yaxis.set_major_formatter(FuncFormatter(lambda x,pos:fmt(x,1)))
    ax.grid(alpha=.25); ax.spines[['top','right']].set_visible(False)
axes[-1].set_xlabel('Epoch')
fig.legend(*axes[0].get_legend_handles_labels(),loc='upper center',ncol=3,frameon=False)
fig.tight_layout(rect=(0,0,1,.91))
fig.savefig(BOOK/'gambar/bab4-kurva-validasi.pdf',bbox_inches='tight')
fig.savefig(BOOK/'build/bab4-qa/kurva-validasi.png',dpi=170,bbox_inches='tight')
plt.close(fig)
image_src = ROOT/'latex/IEEE-Conference/gambar/paper_figG_cases_4x4.png'
inputs.add(image_src)
shutil.copyfile(image_src,BOOK/'gambar/bab4-contoh-target.png')
evidence = {'inputs':[{ 'path':str(p.relative_to(ROOT)), 'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in sorted(inputs)], 'training':training,'source':overall,'ablation':abl,'transfer':transfer,'efficiency':efficiency,'country_note':'Rounded values reused from IEEE main.tex; corroborated by notebook outputs.'}
(BOOK/'build/bab4-qa/evidence.json').write_text(json.dumps(evidence,indent=2))
print(json.dumps({k:evidence[k] for k in ['training','ablation','transfer','efficiency']},indent=2))
